const assert = require('node:assert/strict');
const fs = require('node:fs');
const path = require('node:path');
const vm = require('node:vm');
const source = fs.readFileSync(path.join(__dirname, '..', 'app.js'), 'utf8').split("\n$$('[data-go]')")[0];
const context = vm.createContext({ URLSearchParams, location: { search: '' }, localStorage: { getItem: () => null }, window: {} });
vm.runInContext(source, context);
const run = code => vm.runInContext(code, context);
run('state.cash = 99995; updateCurrentSnapshot()');
assert.equal(run('previousTotal()'), 100000, 'First day P&L uses initial funding');
assert.equal(run('state.snapshots[0].total'), 99995, 'Chart reflects same-day transaction costs');
assert.equal(run('state.snapshots[0].daily'), -5);
run('state.day = 1; state.cash += 104; state.snapshots.push({day: 1, total: state.cash}); updateCurrentSnapshot()');
assert.equal(run('totalValue() - previousTotal()'), 104, 'Next day must not count yesterday transaction fees again');
assert.equal(run('state.snapshots[1].daily'), 104);
run('state.cash -= 3; updateCurrentSnapshot()');
assert.equal(run('state.snapshots[1].daily'), 101, 'Current-day costs belong to current-day P&L');
assert.equal(run('state.snapshots[0].total'), 99995, 'Current-day actions cannot rewrite prior close');
console.log('Account snapshots passed: same-day costs, daily baselines, and chart/equity consistency.');
